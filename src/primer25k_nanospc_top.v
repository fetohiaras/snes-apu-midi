`timescale 1ns/1ps

// SNES APU MIDI synthesizer for the Sipeed Tang Primer 25K.
//
//   midi_rx (UART 8N1) -> uart_rx -> midi_parser -> midi_mailbox
//     -> APU I/O ports -> SPC700 MIDI driver -> S-DSP -> i2s_tx -> PCM5102A
//                                                      \-> pc_audio_tx -> uart_tx
//
// BOOT_IMAGE is the A-RAM/register image the APU boots from; by default the
// MIDI driver image built by tools/build_midi_image.py (see README).
//
// midi_rx/uart_tx are the dock's BL616 USB-serial link to the PC, shared by
// MIDI in and (with PC_AUDIO) a mono audio stream out, so both run at
// UART_BAUD. The BL616 bridge is only reliable at standard low rates, so the
// default stream is 8-bit mu-law at fs/4 (7984 Hz), which fits 115200 baud;
// PC_AUDIO_FORMAT = 0 (14-bit, full rate) needs a >= 800 kbaud link. For a
// DIN-MIDI receiver use UART_BAUD = 31250 and PC_AUDIO = 0.
module primer25k_nanospc_top #(
    parameter         BOOT_IMAGE      = "src/data/midi_boot.spc.hex",
    parameter integer UART_BAUD       = 115200,
    parameter integer PC_AUDIO        = 1,
    parameter integer PC_AUDIO_FORMAT = 1,
    parameter integer PC_AUDIO_DECIM  = 4,
    // The BL616 bridge locks up if its ~7 KB receive buffer overflows while
    // the PC is not reading, so audio is only streamed while Active Sensing
    // bytes (0xFE, sent by the bridge script only while it reads the audio)
    // keep arriving on midi_rx. Other MIDI traffic does not start it.
    parameter integer PC_AUDIO_KEEPALIVE_MS = 300,
    // Diagnostics: a 0xF9 byte on midi_rx (ignored by the MIDI parser)
    // requests a status packet on uart_tx; see tools/midi_bridge.py --diag.
    parameter integer DIAG = 1,
    // USB host bring-up on the dock's USB-A port (usb_host_probe): reads
    // the attached device's descriptor; 0xFD on midi_rx requests its status
    // packet. Adds a second PLL for the 48 MHz USB clock.
    parameter integer USB_HOST = 1
) (
    input  wire clk_50m,
    input  wire midi_rx,
    output wire uart_tx,
    output wire led_ready,
    // PCM5102A: SCK tied low (internal PLL), FMT low (I2S).
    output wire i2s_bclk,
    output wire i2s_lrclk,
    output wire i2s_sdata
`ifndef VERILATOR
    // Dock USB-A host port: L6 = D+, K6 = D- (15k pulldowns on the dock)
    ,inout  wire usb_dp
    ,inout  wire usb_dn
`endif
`ifdef VERILATOR
    // These ports exist solely in the C++ simulation model.  They are absent
    // from the synthesis elaboration and therefore do not consume FPGA pins.
    ,output wire        sim_running
    ,output wire        sim_snd_rdy
    ,output wire [15:0] sim_audio_l
    ,output wire [15:0] sim_audio_r
    ,output wire        sim_ev_valid
    ,output wire [7:0]  sim_ev_status
    ,output wire [6:0]  sim_ev_data1
    ,output wire [6:0]  sim_ev_data2
    ,output wire [15:0] sim_mb_sent
    ,output wire        sim_mb_dropped
    ,output wire        sim_mb_timeout
    ,output wire        sim_mb_busy
    ,output wire        sim_pc_overrun
    // USB: the testbench supplies the 48 MHz clock and resolves the bus
    ,input  wire        sim_clk48
    ,input  wire        sim_usb_dp
    ,input  wire        sim_usb_dn
    ,output wire        sim_usb_tx_dp
    ,output wire        sim_usb_tx_dn
    ,output wire        sim_usb_tx_oen
`endif
);

    localparam integer DCLK_HZ = 24528000;

    // ------------------------------------------------------------------------
    // Clock and power-on reset
    // ------------------------------------------------------------------------
    // Gowin_PLL is generated by the Gowin IP Core Generator.  Its mdclk port
    // clocks the generated PLL initialisation controller; use the stable board
    // clock for both inputs.
    wire dclk;
    wire clk48;     // USB full speed (USB_HOST only)

`ifdef VERILATOR
    // The behavioural simulation has no Gowin PLL primitive.  The simulation
    // harness supplies the desired clock rate; hardware always uses the IP.
    assign dclk  = clk_50m;
    assign clk48 = sim_clk48;
`else
    Gowin_PLL pll_dsp (
        .clkin  (clk_50m),
        .clkout0(dclk),
        .mdclk  (clk_50m)
    );

    generate
        if (USB_HOST != 0) begin : g_pll_usb
            Gowin_PLL48 pll_usb (
                .clkin  (clk_50m),
                .clkout0(clk48),
                .mdclk  (clk_50m)
            );
        end else begin : g_no_pll_usb
            assign clk48 = 1'b0;
        end
    endgenerate
`endif

    // There is no external reset in this first board test.  Hold the APU in
    // reset for about 10.5 ms after configuration, allowing the PLL's internal
    // startup sequence to settle before the parser begins writing state.
    reg [18:0] por_count = 19'd0;
    wire resetn = &por_count;

    always @(posedge clk_50m) begin
        if (!resetn)
            por_count <= por_count + 19'd1;
    end

    // ------------------------------------------------------------------------
    // MIDI input
    // ------------------------------------------------------------------------
    wire [7:0] rx_byte;
    wire       rx_valid;
    wire       ev_valid;
    wire [7:0] ev_status;
    wire [6:0] ev_data1;
    wire [6:0] ev_data2;

    uart_rx #(.CLK_HZ(DCLK_HZ), .BAUD(UART_BAUD)) midi_uart (
        .clk       (dclk),
        .resetn    (resetn),
        .rx        (midi_rx),
        .data      (rx_byte),
        .valid     (rx_valid),
        .frame_err ()
    );

    midi_parser parser (
        .clk       (dclk),
        .resetn    (resetn),
        .in_valid  (rx_valid),
        .in_byte   (rx_byte),
        .ev_valid  (ev_valid),
        .ev_status (ev_status),
        .ev_data1  (ev_data1),
        .ev_data2  (ev_data2)
    );

    // USB-MIDI bytes from the host port (USB_HOST; see the USB section below)
    // go through their own parser, so running status on one input can never
    // mix with the other; the events are merged in front of the mailbox.
    wire       usb_byte_valid;
    wire [7:0] usb_byte;
    wire       uev_valid;
    wire [7:0] uev_status;
    wire [6:0] uev_data1;
    wire [6:0] uev_data2;

    midi_parser usb_parser (
        .clk       (dclk),
        .resetn    (resetn),
        .in_valid  (usb_byte_valid),
        .in_byte   (usb_byte),
        .ev_valid  (uev_valid),
        .ev_status (uev_status),
        .ev_data1  (uev_data1),
        .ev_data2  (uev_data2)
    );

    // UART events go straight through; a USB event that collides with one
    // waits a clock. One entry is enough: USB bytes (and so events) are at
    // least two clocks apart, UART events thousands.
    reg        uhold_valid = 1'b0;
    reg  [7:0] uhold_status = 8'd0;
    reg  [6:0] uhold_data1 = 7'd0, uhold_data2 = 7'd0;
    wire       mev_valid  = ev_valid | uhold_valid | uev_valid;
    wire [7:0] mev_status = ev_valid ? ev_status : uhold_valid ? uhold_status : uev_status;
    wire [6:0] mev_data1  = ev_valid ? ev_data1  : uhold_valid ? uhold_data1  : uev_data1;
    wire [6:0] mev_data2  = ev_valid ? ev_data2  : uhold_valid ? uhold_data2  : uev_data2;

    always @(posedge dclk) begin
        if (!resetn) begin
            uhold_valid <= 1'b0;
        end else if (uev_valid && (ev_valid || uhold_valid)) begin
            uhold_valid  <= 1'b1;
            uhold_status <= uev_status;
            uhold_data1  <= uev_data1;
            uhold_data2  <= uev_data2;
        end else if (!ev_valid) begin
            uhold_valid <= 1'b0;
        end
    end

    // ------------------------------------------------------------------------
    // Mailbox -> APU
    // ------------------------------------------------------------------------
    wire        apu_running;
    wire [1:0]  port_a;
    wire        port_wr_n;
    wire        port_cs;
    wire [7:0]  port_din;
    wire [7:0]  port_dout;
    wire [15:0] mb_sent;
    wire        mb_dropped;
    wire        mb_timeout;
    wire        mb_busy;

    midi_mailbox mb (
        .clk         (dclk),
        .resetn      (resetn),
        .apu_running (apu_running),
        .ev_valid    (mev_valid),
        .ev_status   (mev_status),
        .ev_data1    (mev_data1),
        .ev_data2    (mev_data2),
        .port_a      (port_a),
        .port_wr_n   (port_wr_n),
        .port_cs     (port_cs),
        .port_din    (port_din),
        .port_dout   (port_dout),
        .sent_count  (mb_sent),
        .dropped     (mb_dropped),
        .ack_timeout (mb_timeout),
        .busy        (mb_busy)
    );

    wire        snd_rdy;
    wire [15:0] audio_l;
    wire [15:0] audio_r;

    apu_core #(
        .MEM_INIT_FILE(BOOT_IMAGE)
    ) apu (
        .clk       (dclk),
        .resetn    (resetn),
        .running   (apu_running),
        .port_a    (port_a),
        .port_wr_n (port_wr_n),
        .port_cs   (port_cs),
        .port_din  (port_din),
        .port_dout (port_dout),
        .snd_rdy   (snd_rdy),
        .audio_l   (audio_l),
        .audio_r   (audio_r),
        .dbg_sum_a    (dbg_sum_a),
        .dbg_sum_b    (dbg_sum_b),
        .dbg_sum_done (dbg_sum_done),
        .dbg_boot_pc  (dbg_boot_pc),
        .dbg_smp_a    (dbg_smp_a),
        .dbg_page05   (dbg_page05),
        .dbg_dsp_wr   (dbg_dsp_wr),
        .dbg_kon_wr   (dbg_kon_wr)
    );

    // ------------------------------------------------------------------------
    // I2S output
    // ------------------------------------------------------------------------
    // Reset only by power-on so the DAC sees stable clocks (and silence)
    // while the SPC image is still being parsed.
    i2s_tx i2s (
        .clk          (dclk),
        .resetn       (resetn),
        .sample_valid (snd_rdy),
        .sample_l     (audio_l),
        .sample_r     (audio_r),
        .bclk         (i2s_bclk),
        .lrclk        (i2s_lrclk),
        .sdata        (i2s_sdata)
    );

    // ------------------------------------------------------------------------
    // Audio to the PC over the USB-serial link
    // ------------------------------------------------------------------------
    wire pc_overrun;
    wire pc_busy;
    wire audio_tx;
    wire diag_req = rx_valid && (rx_byte == 8'hF9);

    localparam integer KEEPALIVE_CLKS = (DCLK_HZ / 1000) * PC_AUDIO_KEEPALIVE_MS;
    localparam integer KA_W = $clog2(KEEPALIVE_CLKS + 1);
    localparam [KA_W-1:0] KA_LOAD = KEEPALIVE_CLKS[KA_W-1:0];
    reg [KA_W-1:0] pc_keepalive = {KA_W{1'b0}};
    wire           pc_listening = (pc_keepalive != {KA_W{1'b0}});

    always @(posedge dclk) begin
        if (!resetn)
            pc_keepalive <= {KA_W{1'b0}};
        else if (rx_valid && rx_byte == 8'hFE)
            pc_keepalive <= KA_LOAD;
        else if (pc_listening)
            pc_keepalive <= pc_keepalive - 1'b1;
    end

    generate
        if (PC_AUDIO != 0) begin : g_pc_audio
            pc_audio_tx #(
                .CLK_HZ(DCLK_HZ), .BAUD(UART_BAUD),
                .FORMAT(PC_AUDIO_FORMAT), .DECIM(PC_AUDIO_DECIM)
            ) pc_audio (
                .clk          (dclk),
                .resetn       (resetn),
                .sample_valid (snd_rdy & apu_running & pc_listening),
                .sample_l     (audio_l),
                .sample_r     (audio_r),
                .tx           (audio_tx),
                .overrun      (pc_overrun),
                .busy         (pc_busy)
            );
        end else begin : g_no_pc_audio
            assign audio_tx   = 1'b1;
            assign pc_overrun = 1'b0;
            assign pc_busy    = 1'b0;
        end
    endgenerate

    // ------------------------------------------------------------------------
    // Diagnostic status packet (22 bytes, little-endian fields)
    // ------------------------------------------------------------------------
    //   0-1  A5 5A           magic
    //   2-5  sum A, sum B    A-RAM image checksum computed at boot
    //   6-7  boot PC         SPC700 PC loaded from the image header
    //   8    flags           {sum_done, running, audio_seen, 0,
    //                         mb_dropped, mb_timeout, pc_overrun, mb_busy}
    //   9-10 mailbox sent    commands acknowledged by the driver
    //   11   port 3          last value the SPC700 wrote to $F7 (its ack)
    //   12-13 SPC700 address snapshot
    //   14-15 SPC700 cycles in page $05 (driver code), saturating
    //   16-17 SPC700 writes to $F3 (DSP data)
    //   18   ... of which to KON ($4C)
    //   19-20 peak |sample| of the APU output
    //   21   XOR of bytes 0-20
    reg [14:0] sample_count = 15'd0;
    reg        audio_seen = 1'b0;
    wire [15:0] dbg_sum_a, dbg_sum_b, dbg_boot_pc, dbg_smp_a, dbg_page05, dbg_dsp_wr;
    wire [7:0]  dbg_kon_wr;
    wire        dbg_sum_done;
    wire        diag_tx_line;
    wire        diag_busy;
    reg         diag_pending = 1'b0;
    reg         diag_start = 1'b0;
    reg  [15:0] audio_peak = 16'd0;
    reg  [8*22-1:0] diag_packet = {8*22{1'b0}};

    wire [15:0] abs_l = audio_l[15] ? (~audio_l + 16'd1) : audio_l;
    wire [15:0] abs_r = audio_r[15] ? (~audio_r + 16'd1) : audio_r;

    wire [8*21-1:0] diag_body = {
        audio_peak, dbg_kon_wr, dbg_dsp_wr, dbg_page05, dbg_smp_a, port_dout,
        mb_sent, {dbg_sum_done, apu_running, audio_seen, 1'b0, mb_dropped, mb_timeout, pc_overrun, mb_busy},
        dbg_boot_pc, dbg_sum_b, dbg_sum_a, 8'h5A, 8'hA5
    };
    reg  [7:0] diag_xor;
    integer    di;
    always @* begin
        diag_xor = 8'h00;
        for (di = 0; di < 21; di = di + 1)
            diag_xor = diag_xor ^ diag_body[8*di +: 8];
    end

    always @(posedge dclk) begin
        diag_start <= 1'b0;
        if (!resetn) begin
            diag_pending <= 1'b0;
            audio_peak   <= 16'd0;
        end else begin
            if (apu_running && snd_rdy) begin
                if (abs_l > audio_peak) audio_peak <= abs_l;
                else if (abs_r > audio_peak) audio_peak <= abs_r;
            end
            if (DIAG != 0 && diag_req)
                diag_pending <= 1'b1;
            // Wait for the audio stream to go quiet, then snapshot and send.
            if (diag_pending && !pc_listening && !pc_busy && !diag_busy && !usb_diag_busy && !usb_diag_start) begin
                diag_packet  <= {diag_xor, diag_body};
                diag_start   <= 1'b1;
                diag_pending <= 1'b0;
            end
        end
    end

    diag_tx #(.CLK_HZ(DCLK_HZ), .BAUD(UART_BAUD), .N(22)) diag (
        .clk    (dclk),
        .resetn (resetn),
        .start  (diag_start),
        .data   (diag_packet),
        .tx     (diag_tx_line),
        .busy   (diag_busy)
    );

    // ------------------------------------------------------------------------
    // USB host probe (clk48 domain) and its status packet (0xFD request)
    // ------------------------------------------------------------------------
    //   0-1  A5 5B           magic
    //   2    state           usb_host_probe: 0 detached, 1 reset, 2 recover,
    //                        3 setup, 4 data in, 5 status out, 6 done (no
    //                        MIDI endpoint), 7 status in, 8 set-address wait,
    //                        9 descriptor scan, 10 receiving MIDI
    //   3    {0, 0, req[1:0], 0, 0, line state}
    //                        req: 0 GET_DESCRIPTOR(DEVICE), 1 SET_ADDRESS,
    //                        2 GET_DESCRIPTOR(CONFIGURATION), 3 SET_CONFIGURATION;
    //                        line state {D-, D+} (01 = FS device idle)
    //   4-5  frame number    SOFs sent since the last reset
    //   6    attach count
    //   7    last response PID (00 = timeout)
    //   8-10 NAK, timeout, CRC-error counts (saturating)
    //   11   device descriptor bytes received (18 = complete)
    //   12-29 device descriptor (VID at 20-21, PID at 22-23 of the packet)
    //   30   device address  31  configuration set (0 = not yet)
    //   32-33 L = configuration descriptor bytes received (<= 256)
    //   34   MIDI IN endpoint address (0 = none found)
    //   35   {FIFO overflow, endpoint packet size}
    //   36-37 MIDI bytes received   38-39 bulk packets accepted
    //   40.. configuration descriptor (L bytes)
    //   40+L XOR of all previous bytes
    wire       usb_diag_req = rx_valid && (rx_byte == 8'hFD);
    wire       usb_diag_tx_line;
    wire       usb_diag_busy;
    wire       usb_diag_start;

    generate
        if (USB_HOST != 0) begin : g_usb
            // Reset: hold the USB domain until the board reset is released.
            reg [2:0] rst48_sync = 3'b111;
            always @(posedge clk48)
                rst48_sync <= {rst48_sync[1:0], ~resetn};
            wire rst48 = rst48_sync[2];

            wire [7:0] utx_data, urx_data;
            wire       utx_valid, utx_ready, urx_valid, urx_active;
            wire [1:0] linestate;
            wire       bus_reset;
            wire       phy_tx_dp, phy_tx_dn, phy_tx_oen;
            wire       phy_rx_dp, phy_rx_dn, phy_rx_rcv;

`ifdef VERILATOR
            assign phy_rx_dp      = sim_usb_dp;
            assign phy_rx_dn      = sim_usb_dn;
            assign phy_rx_rcv     = sim_usb_dp & ~sim_usb_dn;
            assign sim_usb_tx_dp  = phy_tx_dp;
            assign sim_usb_tx_dn  = phy_tx_dn;
            assign sim_usb_tx_oen = phy_tx_oen;
`else
            // Single-ended drive straight from the PHY (usb_transceiver.v in
            // mode 1); the receiver is the D+/D- pair itself.
            assign usb_dp     = phy_tx_oen ? 1'bz : phy_tx_dp;
            assign usb_dn     = phy_tx_oen ? 1'bz : phy_tx_dn;
            assign phy_rx_dp  = usb_dp;
            assign phy_rx_dn  = usb_dn;
            assign phy_rx_rcv = usb_dp & ~usb_dn;
`endif

            usb_fs_phy phy (
                .clk_i(clk48), .rst_i(rst48),
                .utmi_data_out_i(utx_data), .utmi_txvalid_i(utx_valid),
                .utmi_op_mode_i(2'b00), .utmi_xcvrselect_i(2'b01), .utmi_termselect_i(1'b0),
                .utmi_dppulldown_i(1'b1), .utmi_dmpulldown_i(1'b1),
                .usb_rx_rcv_i(phy_rx_rcv), .usb_rx_dp_i(phy_rx_dp), .usb_rx_dn_i(phy_rx_dn),
                .usb_reset_assert_i(bus_reset),
                .utmi_data_in_o(urx_data), .utmi_txready_o(utx_ready), .utmi_rxvalid_o(urx_valid),
                .utmi_rxactive_o(urx_active), .utmi_rxerror_o(), .utmi_linestate_o(linestate),
                .usb_tx_dp_o(phy_tx_dp), .usb_tx_dn_o(phy_tx_dn), .usb_tx_oen_o(phy_tx_oen),
                .usb_reset_detect_o(), .usb_en_o()
            );

            wire [3:0]  st;
            wire [1:0]  req;
            wire [6:0]  dev_addr;
            wire [7:0]  config_value;
            wire [10:0] frame;
            wire [7:0]  attach_count, last_pid, nak_count, timeout_count, crc_count;
            wire [4:0]  desc_len;
            wire [8*18-1:0] desc;
            wire [8:0]  cfg_len;
            wire [7:0]  midi_ep;
            wire [6:0]  midi_ep_size;
            wire [15:0] midi_bytes, bulk_packets;
            wire        m_we, m_commit, m_rollback, m_overflow;
            wire [7:0]  m_wdata;
            wire        cfg_we;
            wire [7:0]  cfg_waddr, cfg_wdata;

            usb_host_probe #(.USB_CLK_HZ(48000000)) probe (
                .clk(clk48), .rst(rst48),
                .utmi_data_o(utx_data), .utmi_txvalid_o(utx_valid), .utmi_txready_i(utx_ready),
                .utmi_data_i(urx_data), .utmi_rxvalid_i(urx_valid), .utmi_rxactive_i(urx_active),
                .utmi_linestate_i(linestate), .usb_reset_o(bus_reset),
                .cfg_we(cfg_we), .cfg_waddr(cfg_waddr), .cfg_wdata(cfg_wdata),
                .midi_we(m_we), .midi_wdata(m_wdata), .midi_commit(m_commit), .midi_rollback(m_rollback),
                .state(st), .req(req), .dev_addr(dev_addr), .config_value(config_value),
                .frame(frame), .attach_count(attach_count), .last_pid(last_pid),
                .nak_count(nak_count), .timeout_count(timeout_count), .crc_count(crc_count),
                .desc_len(desc_len), .desc(desc), .cfg_len(cfg_len),
                .midi_ep(midi_ep), .midi_ep_size(midi_ep_size), .midi_bytes(midi_bytes),
                .bulk_packets(bulk_packets)
            );

            // MIDI bytes to the dclk domain (commit/rollback per USB packet)
            usb_midi_fifo midi_fifo (
                .wclk(clk48), .wrst(rst48), .we(m_we), .wdata(m_wdata),
                .commit(m_commit), .rollback(m_rollback), .overflow(m_overflow),
                .rclk(dclk), .rresetn(resetn), .ready(1'b1),
                .valid(usb_byte_valid), .data(usb_byte)
            );

            // Configuration descriptor: written at 48 MHz, read on dclk. The
            // probe only writes it during the configuration read, so a read
            // in DONE sees stable data.
            reg [7:0] cfg_mem [0:255];
            reg [7:0] cfg_raddr = 8'd0;
            reg [7:0] cfg_q = 8'd0;
            always @(posedge clk48)
                if (cfg_we) cfg_mem[cfg_waddr] <= cfg_wdata;
            always @(posedge dclk)
                cfg_q <= cfg_mem[cfg_raddr];

            // Snapshot handshake: dclk toggles req, clk48 captures the status
            // and toggles ack; the snapshot is stable by the time dclk sees it.
            localparam integer HDR = 40;
            reg            req_t = 1'b0, ack48_t = 1'b0;
            reg  [2:0]     req_sync = 3'b000, ack_sync = 3'b000;
            reg            waiting = 1'b0, pending = 1'b0, ready = 1'b0;
            reg  [8*38-1:0] snap = {8*38{1'b0}};

            always @(posedge clk48) begin
                req_sync <= {req_sync[1:0], req_t};
                if (req_sync[2] != req_sync[1]) begin
                    snap <= {bulk_packets, midi_bytes, m_overflow, midi_ep_size, midi_ep,
                             7'd0, cfg_len, config_value, 1'b0, dev_addr,
                             desc, 3'b000, desc_len, crc_count, timeout_count, nak_count,
                             last_pid, attach_count, 5'd0, frame,
                             2'b00, req, 2'b00, linestate, 4'd0, st};
                    ack48_t <= ~ack48_t;
                end
            end

            // Byte-at-a-time sender: header, then the RAM, then the XOR.
            localparam [2:0] T_IDLE = 3'd0, T_LOAD = 3'd1, T_FETCH = 3'd2, T_SEND = 3'd3,
                             T_HOLD = 3'd4, T_WAIT = 3'd5;
            reg  [2:0] ts = T_IDLE;
            reg  [8:0] idx = 9'd0;
            reg  [7:0] sum = 8'd0;
            reg  [7:0] tx_byte = 8'd0;
            reg        tx_start = 1'b0;
            wire       byte_busy;
            wire [9:0] total = HDR + {1'b0, snap[8*30 +: 9]};      // index of the XOR byte
            wire [7:0] hdr_byte = idx == 9'd0 ? 8'hA5 : idx == 9'd1 ? 8'h5B :
                                  snap[8*(idx - 9'd2) +: 8];
            wire [7:0] cur_byte = {1'b0, idx} == total ? sum :
                                  idx < HDR[8:0] ? hdr_byte : cfg_q;
            wire       launch = ts == T_IDLE && ready && !pc_listening && !pc_busy &&
                                !diag_pending && !diag_start && !diag_busy;

            always @(posedge dclk) begin
                tx_start <= 1'b0;
                ack_sync <= {ack_sync[1:0], ack48_t};
                if (!resetn) begin
                    pending <= 1'b0;
                    waiting <= 1'b0;
                    ready   <= 1'b0;
                    ts      <= T_IDLE;
                end else begin
                    if (usb_diag_req)
                        pending <= 1'b1;
                    if (pending && !waiting && !ready && ts == T_IDLE) begin
                        req_t   <= ~req_t;
                        waiting <= 1'b1;
                        pending <= 1'b0;
                    end
                    if (waiting && ack_sync[2] != ack_sync[1]) begin
                        waiting <= 1'b0;
                        ready   <= 1'b1;
                    end
                    case (ts)
                    T_IDLE:  if (launch) begin   // same rules as the main packet; it has priority
                                 ready <= 1'b0;
                                 idx   <= 9'd0;
                                 sum   <= 8'd0;
                                 ts    <= T_LOAD;
                             end
                    T_LOAD:  begin cfg_raddr <= 8'(idx - HDR[8:0]); ts <= T_FETCH; end
                    T_FETCH: ts <= T_SEND;     // cfg_q valid next cycle
                    T_SEND:  begin
                                 tx_byte  <= cur_byte;
                                 tx_start <= 1'b1;
                                 sum      <= sum ^ cur_byte;
                                 ts       <= T_HOLD;
                             end
                    T_HOLD:  ts <= T_WAIT;     // byte_busy rises
                    default: if (!byte_busy) begin
                                 if ({1'b0, idx} == total) begin
                                     ts <= T_IDLE;
                                 end else begin
                                     idx <= idx + 9'd1;
                                     ts  <= T_LOAD;
                                 end
                             end
                    endcase
                end
            end

            diag_tx #(.CLK_HZ(DCLK_HZ), .BAUD(UART_BAUD), .N(1)) usb_diag (
                .clk    (dclk),
                .resetn (resetn),
                .start  (tx_start),
                .data   (tx_byte),
                .tx     (usb_diag_tx_line),
                .busy   (byte_busy)
            );
            assign usb_diag_busy  = ts != T_IDLE;
            assign usb_diag_start = launch;
        end else begin : g_no_usb
            assign usb_diag_start   = 1'b0;
            assign usb_diag_tx_line = 1'b1;
            assign usb_diag_busy    = 1'b0;
            assign usb_byte_valid   = 1'b0;
            assign usb_byte         = 8'd0;
`ifndef VERILATOR
            assign usb_dp = 1'bz;
            assign usb_dn = 1'bz;
`else
            assign sim_usb_tx_dp  = 1'b0;
            assign sim_usb_tx_dn  = 1'b0;
            assign sim_usb_tx_oen = 1'b1;
`endif
        end
    endgenerate

    assign uart_tx = diag_busy ? diag_tx_line : usb_diag_busy ? usb_diag_tx_line : audio_tx;

    // ------------------------------------------------------------------------
    // Status LED
    // ------------------------------------------------------------------------
    // Driven from the 50 MHz board clock so it can report a dead PLL too:
    //   off          power-on reset
    //   1 blink      dclk (PLL output) not running
    //   2 blinks     dclk running, APU not started (boot/SPC parser stuck)
    //   3 blinks     mailbox error (driver not acknowledging, command FIFO
    //                overflow) or PC audio overrun
    //   solid on     APU running, no audio yet
    //   ~1 Hz blink  audio playing (bit 14 of the sample counter)
    // Blink codes repeat every 2^27 board clocks (~2.7 s).
    reg        dclk_toggle = 1'b0;

    always @(posedge dclk) begin
        dclk_toggle <= ~dclk_toggle;
        if (!apu_running) begin
            sample_count <= 15'd0;
            audio_seen   <= 1'b0;
        end else if (snd_rdy) begin
            sample_count <= sample_count + 15'd1;
            if ((audio_l != 16'h0000) || (audio_r != 16'h0000))
                audio_seen <= 1'b1;
        end
    end

    wire error_flag = mb_timeout | mb_dropped | pc_overrun;

    reg [2:0]  toggle_sync  = 3'b000;
    reg [1:0]  running_sync = 2'b00;
    reg [1:0]  audio_sync   = 2'b00;
    reg [1:0]  error_sync   = 2'b00;
    reg [1:0]  blink_sync   = 2'b00;
    reg [9:0]  dclk_idle    = 10'h3FF;
    reg [26:0] led_seq      = 27'd0;
    reg        led_q        = 1'b0;

    wire dclk_ok = (dclk_idle != 10'h3FF);
    wire [1:0] blinks = !dclk_ok          ? 2'd1 :
                        !running_sync[1]  ? 2'd2 :
                        error_sync[1]     ? 2'd3 : 2'd0;
    wire [3:0] slot = led_seq[26:23];

    always @(posedge clk_50m) begin
        toggle_sync  <= {toggle_sync[1:0], dclk_toggle};
        running_sync <= {running_sync[0], apu_running};
        audio_sync   <= {audio_sync[0], audio_seen};
        error_sync   <= {error_sync[0], error_flag};
        blink_sync   <= {blink_sync[0], sample_count[14]};
        led_seq      <= led_seq + 27'd1;

        if (toggle_sync[2] != toggle_sync[1])
            dclk_idle <= 10'd0;
        else if (dclk_ok)
            dclk_idle <= dclk_idle + 10'd1;

        if (!resetn)
            led_q <= 1'b0;
        else if (blinks != 2'd0)
            led_q <= !slot[0] && (slot[3:1] < {1'b0, blinks});
        else
            led_q <= !audio_sync[1] ? 1'b1 : blink_sync[1];
    end

    assign led_ready = led_q;

`ifdef VERILATOR
    assign sim_running    = apu_running;
    assign sim_snd_rdy    = snd_rdy;
    assign sim_audio_l    = audio_l;
    assign sim_audio_r    = audio_r;
    assign sim_ev_valid   = ev_valid;
    assign sim_ev_status  = ev_status;
    assign sim_ev_data1   = ev_data1;
    assign sim_ev_data2   = ev_data2;
    assign sim_mb_sent    = mb_sent;
    assign sim_mb_dropped = mb_dropped;
    assign sim_mb_timeout = mb_timeout;
    assign sim_mb_busy    = mb_busy;
    assign sim_pc_overrun = pc_overrun;
`endif

